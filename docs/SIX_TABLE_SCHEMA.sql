-- Six-table Oracle banking schema, extracted after V22. Chat tables remain separate.

  CREATE TABLE "NEXA_APP"."CUSTOMERS"
   (	"ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"USER_ID" VARCHAR2(26),
	"FULL_NAME" VARCHAR2(160) NOT NULL ENABLE,
	"EMAIL" VARCHAR2(254) NOT NULL ENABLE,
	"PHONE_NUMBER" VARCHAR2(32),
	"DATE_OF_BIRTH" DATE,
	"ADDRESS" VARCHAR2(255),
	"CREATED_AT" TIMESTAMP (6) NOT NULL ENABLE,
	"UPDATED_AT" TIMESTAMP (6) NOT NULL ENABLE,
	"STATUS" VARCHAR2(24) DEFAULT 'ACTIVE' NOT NULL ENABLE,
	"ROLE" VARCHAR2(24) DEFAULT 'CUSTOMER' NOT NULL ENABLE,
	 PRIMARY KEY ("ID")
  USING INDEX  ENABLE,
	 UNIQUE ("USER_ID")
  USING INDEX  ENABLE,
	 UNIQUE ("EMAIL")
  USING INDEX  ENABLE,
	 UNIQUE ("PHONE_NUMBER")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_CUSTOMER_ACCESS_STATUS" CHECK (status IN ('ACTIVE','LOCKED','DISABLED')) ENABLE,
	 CONSTRAINT "CK_CUSTOMER_ACCESS_ROLE" CHECK (role IN ('CUSTOMER','SUPPORT_AGENT','FRAUD_ANALYST','ADMIN')) ENABLE
   ) ;

  CREATE TABLE "NEXA_APP"."CUSTOMER_CREDENTIALS"
   (	"ID" VARCHAR2(26),
	"USER_ID" VARCHAR2(26) NOT NULL ENABLE,
	"CREDENTIAL_TYPE" VARCHAR2(16) NOT NULL ENABLE,
	"PASSWORD_HASH" VARCHAR2(100),
	"TOKEN_HASH" CHAR(64),
	"EXPIRES_AT" TIMESTAMP (6) WITH TIME ZONE,
	"REVOKED_AT" TIMESTAMP (6) WITH TIME ZONE,
	"CREATED_AT" TIMESTAMP (6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL ENABLE,
	 CHECK (credential_type IN ('PASSWORD','REFRESH')) ENABLE,
	 CONSTRAINT "CK_CREDENTIAL_SHAPE" CHECK ((credential_type='PASSWORD' AND token_hash IS NULL) OR (credential_type='REFRESH' AND password_hash IS NULL AND token_hash IS NOT NULL AND expires_at IS NOT NULL)) ENABLE,
	 PRIMARY KEY ("ID")
  USING INDEX  ENABLE,
	 UNIQUE ("TOKEN_HASH")
  USING INDEX  ENABLE,
	 FOREIGN KEY ("USER_ID")
	  REFERENCES "NEXA_APP"."CUSTOMERS" ("USER_ID") ENABLE
   ) ;

  CREATE TABLE "NEXA_APP"."ACCOUNTS"
   (	"ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"ACCOUNT_NUMBER" VARCHAR2(30) NOT NULL ENABLE,
	"CUSTOMER_ID" NUMBER,
	"ACCOUNT_NAME" VARCHAR2(120) NOT NULL ENABLE,
	"ACCOUNT_TYPE" VARCHAR2(20) NOT NULL ENABLE,
	"ACCOUNT_CATEGORY" VARCHAR2(20) NOT NULL ENABLE,
	"CURRENCY_CODE" VARCHAR2(3) DEFAULT 'INR' NOT NULL ENABLE,
	"VERSION" NUMBER(19,0) DEFAULT 0 NOT NULL ENABLE,
	"BALANCE" NUMBER(19,2) DEFAULT 0 NOT NULL ENABLE,
	"STATUS" VARCHAR2(20) NOT NULL ENABLE,
	"CREATED_AT" TIMESTAMP (6) NOT NULL ENABLE,
	"UPDATED_AT" TIMESTAMP (6) NOT NULL ENABLE,
	"PRODUCT_ID" VARCHAR2(40),
	"FUNDING_ACCOUNT_ID" NUMBER,
	"PRINCIPAL_AMOUNT" NUMBER(19,2),
	"INTEREST_RATE" NUMBER(9,6),
	"PRODUCT_STATUS" VARCHAR2(32),
	"PRODUCT_TYPE" VARCHAR2(32),
	"NUMBER_MASKED" VARCHAR2(40),
	"DUE_AT" VARCHAR2(40),
	"PERIODIC_PAYMENT" NUMBER(19,2),
	"CREDIT_LIMIT" NUMBER(19,2),
	"MINIMUM_PAYMENT" NUMBER(19,2),
	"APPLICATION_KEY" VARCHAR2(80),
	"LOAN_PURPOSE" VARCHAR2(200),
	"TENURE_MONTHS" NUMBER(10,0),
	"APPROVED_AT" TIMESTAMP (6),
	"CLOSED_AT" TIMESTAMP (6),
	"REVIEWED_BY" VARCHAR2(26),
	"REVIEW_REASON" VARCHAR2(500),
	"REVIEWED_AT" TIMESTAMP (6),
	 CONSTRAINT "CK_ACCOUNTS_CATEGORY" CHECK (ACCOUNT_CATEGORY IN ('CUSTOMER','SYSTEM')) ENABLE,
	 CONSTRAINT "CK_ACCOUNTS_STATUS" CHECK (STATUS IN ('ACTIVE','BLOCKED','CLOSED')) ENABLE,
	 CONSTRAINT "CK_SYSTEM_ACCOUNT_CUSTOMER" CHECK ((ACCOUNT_CATEGORY = 'SYSTEM' AND CUSTOMER_ID IS NULL) OR (ACCOUNT_CATEGORY = 'CUSTOMER' AND CUSTOMER_ID IS NOT NULL)) ENABLE,
	 PRIMARY KEY ("ID")
  USING INDEX  ENABLE,
	 UNIQUE ("ACCOUNT_NUMBER")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_ACCOUNTS_TYPE" CHECK (account_type IN ('SAVINGS','CURRENT','CASH','CLEARING','LOAN','CARD')) ENABLE,
	 UNIQUE ("PRODUCT_ID")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_LOAN_VALUES" CHECK (account_type <> 'LOAN' OR (account_category='CUSTOMER' AND principal_amount>0 AND interest_rate>=0 AND balance>=0)) ENABLE,
	 CONSTRAINT "CK_LOAN_TERMS" CHECK (tenure_months IS NULL OR
 (account_type='LOAN' AND application_key IS NOT NULL AND loan_purpose IS NOT NULL
 AND tenure_months BETWEEN 1 AND 60 AND principal_amount BETWEEN 1000 AND 1000000
 AND interest_rate BETWEEN 0 AND 50 AND periodic_payment>0
 AND (product_status IN ('PENDING_APPROVAL','REJECTED') OR approved_at IS NOT NULL))) ENABLE,
	 CONSTRAINT "FK_ACCOUNTS_CUSTOMER" FOREIGN KEY ("CUSTOMER_ID")
	  REFERENCES "NEXA_APP"."CUSTOMERS" ("ID") ENABLE,
	 FOREIGN KEY ("FUNDING_ACCOUNT_ID")
	  REFERENCES "NEXA_APP"."ACCOUNTS" ("ID") ENABLE,
	 FOREIGN KEY ("REVIEWED_BY")
	  REFERENCES "NEXA_APP"."CUSTOMERS" ("USER_ID") ENABLE
   ) ;

  CREATE TABLE "NEXA_APP"."TRANSACTIONS"
   (	"ID" VARCHAR2(40),
	"TRANSACTION_TYPE" VARCHAR2(20),
	"SOURCE_ACCOUNT_ID" NUMBER,
	"DESTINATION_ACCOUNT_ID" NUMBER,
	"MERCHANT_NAME" VARCHAR2(200),
	"CATEGORY" VARCHAR2(80),
	"PAYMENT_METHOD" VARCHAR2(32),
	"AMOUNT" NUMBER(19,2),
	"STATUS" VARCHAR2(32) NOT NULL ENABLE,
	"CREATED_AT" TIMESTAMP (6) DEFAULT CURRENT_TIMESTAMP NOT NULL ENABLE,
	"COMPLETED_AT" TIMESTAMP (6),
	"RECORD_KIND" VARCHAR2(32) DEFAULT 'PAYMENT' NOT NULL ENABLE,
	"USER_ID" VARCHAR2(26),
	"PARENT_ID" VARCHAR2(40),
	"OPERATION" VARCHAR2(40),
	"TARGET_ID" VARCHAR2(80),
	"TRANSACTION_REFERENCE" VARCHAR2(80),
	"MINIMUM_AMOUNT" NUMBER(19,2),
	"CURRENCY_CODE" VARCHAR2(3),
	"DISPLAY_NAME" VARCHAR2(200),
	"SOURCE_NAME" VARCHAR2(120),
	"SOURCE_MASKED" VARCHAR2(40),
	"RECIPIENT_NAME" VARCHAR2(160),
	"DESTINATION_MASKED" VARCHAR2(40),
	"BANK_NAME" VARCHAR2(160),
	"DESTINATION_HASH" VARCHAR2(64),
	"ROUTING_CODE" VARCHAR2(32),
	"BENEFICIARY_TYPE" VARCHAR2(24),
	"FREQUENCY" VARCHAR2(32),
	"EFFECTIVE_DATE" VARCHAR2(40),
	"END_DATE" VARCHAR2(40),
	"DUE_AT" VARCHAR2(40),
	"EXPIRES_AT" TIMESTAMP (6),
	"UPDATED_AT" TIMESTAMP (6),
	"AUDIT_REASON" VARCHAR2(500),
	"BEFORE_NAME" VARCHAR2(120),
	"AFTER_NAME" VARCHAR2(120),
	"BEFORE_STATUS" VARCHAR2(32),
	"AFTER_STATUS" VARCHAR2(32),
	"INSTALLMENT_NUMBER" NUMBER(10,0),
	"PRINCIPAL_COMPONENT" NUMBER(19,2),
	"INTEREST_COMPONENT" NUMBER(19,2),
	 PRIMARY KEY ("ID")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_PAYMENT_SHAPE" CHECK (record_kind <> 'PAYMENT' OR (amount IS NOT NULL AND amount>0 AND transaction_type IS NOT NULL AND transaction_type IN ('DEPOSIT','WITHDRAWAL','TRANSFER','LOAN_DISBURSEMENT','LOAN_REPAYMENT') AND status IN ('SUCCESS','FAILED','REVERSED') AND (source_account_id IS NOT NULL OR destination_account_id IS NOT NULL))) ENABLE,
	 CONSTRAINT "CK_INSTRUCTION_OWNER" CHECK (record_kind='PAYMENT' OR user_id IS NOT NULL) ENABLE,
	 CONSTRAINT "CK_POSTING_ACCOUNTS" CHECK (
 record_kind <> 'PAYMENT' OR
 (transaction_type='DEPOSIT' AND source_account_id IS NULL AND destination_account_id IS NOT NULL) OR
 (transaction_type='WITHDRAWAL' AND source_account_id IS NOT NULL AND destination_account_id IS NULL) OR
 (transaction_type IN ('TRANSFER','LOAN_DISBURSEMENT','LOAN_REPAYMENT') AND source_account_id IS NOT NULL AND destination_account_id IS NOT NULL AND source_account_id<>destination_account_id)
) ENABLE,
	 CONSTRAINT "CK_MANDATE_AUTHORIZATION" CHECK (
 record_kind <> 'MANDATE' OR operation IS NULL OR
 (operation='TRANSFER' AND source_account_id IS NOT NULL AND destination_account_id IS NOT NULL AND source_account_id<>destination_account_id AND amount IS NOT NULL AND amount>0 AND effective_date IS NOT NULL)
) ENABLE,
	 CONSTRAINT "CK_REVIEW_SHAPE" CHECK (
 record_kind <> 'TRANSFER_REVIEW' OR
 (source_account_id IS NOT NULL AND destination_account_id IS NOT NULL AND source_account_id<>destination_account_id AND amount IS NOT NULL AND amount>0 AND expires_at IS NOT NULL AND
 ((status IN ('READY','CANCELLED') AND transaction_reference IS NULL AND completed_at IS NULL) OR (status='COMPLETED' AND transaction_reference IS NOT NULL AND completed_at IS NOT NULL)))
) ENABLE,
	 CONSTRAINT "CK_TX_RECORD_KIND" CHECK (record_kind IN
 ('PAYMENT','MANDATE','MANDATE_EVENT','BILL','SCHEDULED_PAYMENT','BENEFICIARY','TRANSFER_REVIEW',
 'SIMULATION','LEGACY_TRANSFER','PRODUCT_HISTORY','ADMIN_EVENT','LOAN_INSTALLMENT')) ENABLE,
	 CONSTRAINT "CK_LOAN_INSTALLMENT" CHECK (record_kind <> 'LOAN_INSTALLMENT' OR
 (target_id IS NOT NULL AND installment_number BETWEEN 1 AND 60 AND due_at IS NOT NULL
 AND principal_component IS NOT NULL AND principal_component>0
 AND interest_component IS NOT NULL AND interest_component>=0
 AND amount=principal_component+interest_component AND status IN ('PENDING','PAID'))) ENABLE,
	 CONSTRAINT "FK_TX_SOURCE" FOREIGN KEY ("SOURCE_ACCOUNT_ID")
	  REFERENCES "NEXA_APP"."ACCOUNTS" ("ID") ENABLE,
	 CONSTRAINT "FK_TX_DESTINATION" FOREIGN KEY ("DESTINATION_ACCOUNT_ID")
	  REFERENCES "NEXA_APP"."ACCOUNTS" ("ID") ENABLE,
	 FOREIGN KEY ("USER_ID")
	  REFERENCES "NEXA_APP"."CUSTOMERS" ("USER_ID") ENABLE,
	 FOREIGN KEY ("PARENT_ID")
	  REFERENCES "NEXA_APP"."TRANSACTIONS" ("ID") ENABLE
   ) ;

  CREATE TABLE "NEXA_APP"."JOURNAL_ENTRIES"
   (	"ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"TRANSACTION_ID" VARCHAR2(40) NOT NULL ENABLE,
	"ENTRY_REFERENCE" VARCHAR2(40) NOT NULL ENABLE,
	"ENTRY_TYPE" VARCHAR2(20) NOT NULL ENABLE,
	"STATUS" VARCHAR2(20) NOT NULL ENABLE,
	"CREATED_AT" TIMESTAMP (6) NOT NULL ENABLE,
	 CONSTRAINT "CK_JOURNAL_TYPE" CHECK (ENTRY_TYPE IN ('TRANSACTION','REVERSAL')) ENABLE,
	 CONSTRAINT "CK_JOURNAL_STATUS" CHECK (STATUS IN ('POSTED','REVERSED')) ENABLE,
	 PRIMARY KEY ("ID")
  USING INDEX  ENABLE,
	 UNIQUE ("TRANSACTION_ID")
  USING INDEX  ENABLE,
	 UNIQUE ("ENTRY_REFERENCE")
  USING INDEX  ENABLE,
	 CONSTRAINT "FK_JOURNAL_TRANSACTION" FOREIGN KEY ("TRANSACTION_ID")
	  REFERENCES "NEXA_APP"."TRANSACTIONS" ("ID") ENABLE
   ) ;

  CREATE TABLE "NEXA_APP"."LEDGER_ENTRIES"
   (	"ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"JOURNAL_ENTRY_ID" NUMBER NOT NULL ENABLE,
	"ACCOUNT_ID" NUMBER NOT NULL ENABLE,
	"ENTRY_TYPE" VARCHAR2(10) NOT NULL ENABLE,
	"AMOUNT" NUMBER(19,2) NOT NULL ENABLE,
	"CREATED_AT" TIMESTAMP (6) NOT NULL ENABLE,
	 CONSTRAINT "CK_LEDGER_TYPE" CHECK (ENTRY_TYPE IN ('DEBIT','CREDIT')) ENABLE,
	 CONSTRAINT "CK_LEDGER_AMOUNT" CHECK (AMOUNT > 0) ENABLE,
	 PRIMARY KEY ("ID")
  USING INDEX  ENABLE,
	 CONSTRAINT "FK_LEDGER_JOURNAL" FOREIGN KEY ("JOURNAL_ENTRY_ID")
	  REFERENCES "NEXA_APP"."JOURNAL_ENTRIES" ("ID") ENABLE,
	 CONSTRAINT "FK_LEDGER_ACCOUNT" FOREIGN KEY ("ACCOUNT_ID")
	  REFERENCES "NEXA_APP"."ACCOUNTS" ("ID") ENABLE
   ) ;
