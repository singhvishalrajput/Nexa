-- 1. LOANS: one row for each submitted loan application.
-- APPLICATION_KEY prevents duplicate applications when the same request is retried.
-- OUTSTANDING_AMOUNT is unpaid principal, not principal plus future interest.
-- VERSION is maintained by JPA to detect conflicting updates.
CREATE TABLE LOANS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID NUMBER NOT NULL,
    ACCOUNT_ID NUMBER NOT NULL,
    APPLICATION_KEY VARCHAR2(80) NOT NULL,
    PURPOSE VARCHAR2(200) NOT NULL,
    AMOUNT NUMBER(19,2) NOT NULL,
    INTEREST_RATE NUMBER(5,2) NOT NULL,
    TENURE_MONTHS NUMBER(10) NOT NULL,
    EMI_AMOUNT NUMBER(19,2) NOT NULL,
    OUTSTANDING_AMOUNT NUMBER(19,2) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(24) DEFAULT 'APPROVED' NOT NULL,
    NEXT_DUE_DATE DATE,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    APPROVED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CLOSED_AT TIMESTAMP,
    VERSION NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT FK_LOANS_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(ID),
    CONSTRAINT FK_LOANS_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNTS(ID),
    CONSTRAINT UQ_LOANS_APPLICATION UNIQUE (CUSTOMER_ID, APPLICATION_KEY),
    CONSTRAINT CK_LOANS_AMOUNT CHECK (AMOUNT BETWEEN 1000 AND 1000000),
    CONSTRAINT CK_LOANS_RATE CHECK (INTEREST_RATE BETWEEN 0 AND 50),
    CONSTRAINT CK_LOANS_TENURE CHECK (TENURE_MONTHS BETWEEN 1 AND 60),
    CONSTRAINT CK_LOANS_EMI CHECK (EMI_AMOUNT > 0),
    CONSTRAINT CK_LOANS_OUTSTANDING CHECK (OUTSTANDING_AMOUNT BETWEEN 0 AND AMOUNT),
    CONSTRAINT CK_LOANS_STATUS CHECK (STATUS IN ('APPROVED','ACTIVE','CLOSED')),
    CONSTRAINT CK_LOANS_VERSION CHECK (VERSION >= 0)
);

-- 2. LOAN_INSTALLMENTS: one row for each monthly EMI.
-- TOTAL_AMOUNT = PRINCIPAL_AMOUNT + INTEREST_AMOUNT.
-- PAID_AT stays empty until the EMI is paid.
-- The (ID, LOAN_ID) unique pair lets payments refer to an installment of the same loan.
CREATE TABLE LOAN_INSTALLMENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOAN_ID NUMBER NOT NULL,
    INSTALLMENT_NUMBER NUMBER(10) NOT NULL,
    DUE_DATE DATE NOT NULL,
    PRINCIPAL_AMOUNT NUMBER(19,2) NOT NULL,
    INTEREST_AMOUNT NUMBER(19,2) NOT NULL,
    TOTAL_AMOUNT NUMBER(19,2) NOT NULL,
    STATUS VARCHAR2(24) DEFAULT 'PENDING' NOT NULL,
    PAID_AT TIMESTAMP,
    CONSTRAINT FK_INSTALLMENT_LOAN FOREIGN KEY (LOAN_ID) REFERENCES LOANS(ID),
    CONSTRAINT UQ_INSTALLMENT_NUMBER UNIQUE (LOAN_ID, INSTALLMENT_NUMBER),
    CONSTRAINT UQ_INSTALLMENT_LOAN_ID UNIQUE (ID, LOAN_ID),
    CONSTRAINT CK_INSTALLMENT_NUMBER CHECK (INSTALLMENT_NUMBER BETWEEN 1 AND 60),
    CONSTRAINT CK_INSTALLMENT_PRINCIPAL CHECK (PRINCIPAL_AMOUNT > 0),
    CONSTRAINT CK_INSTALLMENT_INTEREST CHECK (INTEREST_AMOUNT >= 0),
    CONSTRAINT CK_INSTALLMENT_TOTAL CHECK (
        TOTAL_AMOUNT > 0 AND TOTAL_AMOUNT = PRINCIPAL_AMOUNT + INTEREST_AMOUNT),
    CONSTRAINT CK_INSTALLMENT_STATUS CHECK (STATUS IN ('PENDING','PAID')),
    CONSTRAINT CK_INSTALLMENT_PAID CHECK (
        (STATUS = 'PENDING' AND PAID_AT IS NULL)
        OR (STATUS = 'PAID' AND PAID_AT IS NOT NULL))
);

-- 3. LOAN_PAYMENTS: one row each time loan money actually moves.
-- DISBURSEMENT credits the account; EMI_PAYMENT debits it.
-- INSTALLMENT_ID is empty for disbursement and required for an EMI payment.
-- STATUS is always POSTED because failed attempts are rolled back, not stored.
CREATE TABLE LOAN_PAYMENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOAN_ID NUMBER NOT NULL,
    INSTALLMENT_ID NUMBER,
    ACCOUNT_ID NUMBER NOT NULL,
    PAYMENT_REFERENCE VARCHAR2(80) NOT NULL,
    PAYMENT_TYPE VARCHAR2(24) NOT NULL,
    AMOUNT NUMBER(19,2) NOT NULL,
    PRINCIPAL_AMOUNT NUMBER(19,2) NOT NULL,
    INTEREST_AMOUNT NUMBER(19,2) NOT NULL,
    STATUS VARCHAR2(24) DEFAULT 'POSTED' NOT NULL,
    PAID_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_LOAN_PAYMENT_LOAN FOREIGN KEY (LOAN_ID) REFERENCES LOANS(ID),
    CONSTRAINT FK_LOAN_PAYMENT_INSTALLMENT FOREIGN KEY (INSTALLMENT_ID, LOAN_ID)
        REFERENCES LOAN_INSTALLMENTS(ID, LOAN_ID),
    CONSTRAINT FK_LOAN_PAYMENT_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNTS(ID),
    CONSTRAINT UQ_LOAN_PAYMENT_REFERENCE UNIQUE (PAYMENT_REFERENCE),
    CONSTRAINT UQ_LOAN_PAYMENT_INSTALLMENT UNIQUE (INSTALLMENT_ID),
    CONSTRAINT CK_LOAN_PAYMENT_TYPE CHECK (PAYMENT_TYPE IN ('DISBURSEMENT','EMI_PAYMENT')),
    CONSTRAINT CK_LOAN_PAYMENT_STATUS CHECK (STATUS = 'POSTED'),
    CONSTRAINT CK_LOAN_PAYMENT_PRINCIPAL CHECK (PRINCIPAL_AMOUNT > 0),
    CONSTRAINT CK_LOAN_PAYMENT_INTEREST CHECK (INTEREST_AMOUNT >= 0),
    CONSTRAINT CK_LOAN_PAYMENT_TOTAL CHECK (
        AMOUNT > 0 AND AMOUNT = PRINCIPAL_AMOUNT + INTEREST_AMOUNT),
    CONSTRAINT CK_LOAN_PAYMENT_INSTALLMENT CHECK (
        (PAYMENT_TYPE = 'DISBURSEMENT' AND INSTALLMENT_ID IS NULL AND INTEREST_AMOUNT = 0)
        OR (PAYMENT_TYPE = 'EMI_PAYMENT' AND INSTALLMENT_ID IS NOT NULL))
);

-- Prevent a second disbursement for the same loan.
-- CASE selects LOAN_ID only for disbursements; EMI rows do not occupy this index.
CREATE UNIQUE INDEX UQ_LOAN_DISBURSEMENT ON LOAN_PAYMENTS
    (CASE WHEN PAYMENT_TYPE = 'DISBURSEMENT' THEN LOAN_ID ELSE NULL END);

-- These ordinary indexes speed up lookups by account or loan.
CREATE INDEX IDX_LOANS_ACCOUNT ON LOANS(ACCOUNT_ID);
CREATE INDEX IDX_LOAN_PAYMENTS_LOAN ON LOAN_PAYMENTS(LOAN_ID);
CREATE INDEX IDX_LOAN_PAYMENTS_ACCOUNT ON LOAN_PAYMENTS(ACCOUNT_ID);
