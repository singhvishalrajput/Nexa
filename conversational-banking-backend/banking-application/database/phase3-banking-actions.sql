CREATE TABLE BANKING_ACTIONS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONVERSATION_ID NUMBER NOT NULL,
    CUSTOMER_ID NUMBER NOT NULL,
    ACTION_TYPE VARCHAR2(20) NOT NULL,
    SOURCE_ACCOUNT_ID NUMBER,
    DESTINATION_ACCOUNT_ID NUMBER,
    AMOUNT NUMBER(19,2) NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'PENDING_CONFIRMATION' NOT NULL,
    TRANSACTION_ID VARCHAR2(40) UNIQUE,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONFIRMED_AT TIMESTAMP,
    CONSTRAINT FK_ACTION_CONVERSATION FOREIGN KEY (CONVERSATION_ID) REFERENCES CHAT_CONVERSATIONS(ID),
    CONSTRAINT FK_ACTION_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(ID),
    CONSTRAINT FK_ACTION_SOURCE FOREIGN KEY (SOURCE_ACCOUNT_ID) REFERENCES ACCOUNTS(ID),
    CONSTRAINT FK_ACTION_DESTINATION FOREIGN KEY (DESTINATION_ACCOUNT_ID) REFERENCES ACCOUNTS(ID),
    CONSTRAINT FK_ACTION_TRANSACTION FOREIGN KEY (TRANSACTION_ID) REFERENCES TRANSACTIONS(ID),
    CONSTRAINT CK_ACTION_TYPE CHECK (ACTION_TYPE IN ('DEPOSIT','WITHDRAWAL','TRANSFER')),
    CONSTRAINT CK_ACTION_STATUS CHECK (STATUS IN ('PENDING_CONFIRMATION','COMPLETED','CANCELLED')),
    CONSTRAINT CK_ACTION_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_ACTION_ACCOUNTS CHECK (
        (ACTION_TYPE = 'DEPOSIT' AND SOURCE_ACCOUNT_ID IS NULL AND DESTINATION_ACCOUNT_ID IS NOT NULL)
        OR (ACTION_TYPE = 'WITHDRAWAL' AND SOURCE_ACCOUNT_ID IS NOT NULL AND DESTINATION_ACCOUNT_ID IS NULL)
        OR (ACTION_TYPE = 'TRANSFER' AND SOURCE_ACCOUNT_ID IS NOT NULL AND DESTINATION_ACCOUNT_ID IS NOT NULL)
    )
);

COMMIT;
