-- CHAT AND WORKFLOW SUPPORT (four tables, in addition to the six banking tables).
-- Create CUSTOMERS first; its USER_ID must have a unique or primary-key constraint.
-- Mirrors the current V7, V8, V12, V13 and V16 conversation schema.
-- No legacy USERS table, copy-forward operations, demo customers or demo credentials.

-- A customer owns a conversation. Deleting a customer is not cascaded through chat.
CREATE TABLE conversations (
    id VARCHAR2(36) PRIMARY KEY,
    user_id VARCHAR2(26) NOT NULL,
    title VARCHAR2(120 CHAR) DEFAULT 'New conversation' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_chat_customer FOREIGN KEY (user_id) REFERENCES customers(user_id)
);
CREATE INDEX ix_conversations_owner ON conversations(user_id, created_at DESC, id);

-- Each row is one exchange, with an optional versioned banking/workflow snapshot.
-- The unique client ID per conversation makes retries idempotent. The identity
-- sequence supplies ordering; the Java API returns it as text for JS precision.
-- Deleting chat removes its turns, but never financial records or action audit.
CREATE TABLE conversation_turns (
    sequence_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    conversation_id VARCHAR2(36) NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    client_id VARCHAR2(36) NOT NULL,
    source VARCHAR2(5) NOT NULL CHECK (source IN ('TEXT', 'VOICE')),
    intent VARCHAR2(40) NOT NULL,
    user_text CLOB NOT NULL,
    assistant_text CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    banking_content CLOB,
    workflow_content CLOB,
    CONSTRAINT uk_conversation_turn_retry UNIQUE (conversation_id, client_id),
    CONSTRAINT ck_turn_banking_json CHECK (banking_content IS JSON)
);
CREATE INDEX ix_conversation_turn_page ON conversation_turns(conversation_id, sequence_id DESC);

-- Mutable workflow state for draft/review/confirmation UI. It is not a ledger.
-- Like turns, this state is removed when its parent conversation is deleted.
CREATE TABLE conversation_workflows (
    id VARCHAR2(36) PRIMARY KEY,
    conversation_id VARCHAR2(36) NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    state CLOB NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX idx_workflow_conversation ON conversation_workflows(conversation_id, updated_at);

-- Intentionally independent of deletable conversations and workflow rows.
-- No foreign key to either: audit events must survive deletion of chat history.
-- IDs, operation/status and masked references are retained, not raw message text.
-- AMOUNT is the workflow's textual snapshot, not an authoritative money column.
CREATE TABLE conversation_action_events (
    id VARCHAR2(36) PRIMARY KEY,
    action_id VARCHAR2(36) NOT NULL,
    user_id VARCHAR2(26) NOT NULL,
    operation VARCHAR2(40) NOT NULL,
    status VARCHAR2(24) NOT NULL,
    source_account_id VARCHAR2(80),
    target_id VARCHAR2(80),
    amount VARCHAR2(32),
    transaction_reference VARCHAR2(80),
    correlation_id VARCHAR2(128),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX idx_action_audit ON conversation_action_events(action_id, created_at);


