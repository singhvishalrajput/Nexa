-- Preserve the original financial records for audit; no runtime code reads these archives.
-- Preflight before Oracle DDL (which auto-commits): unsupported monetary values require reconciliation.
DECLARE
  invalid_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO invalid_count FROM bank_accounts
   WHERE account_type NOT IN ('SAVINGS','CURRENT') OR currency_code <> 'INR'
      OR available_balance <> ledger_balance OR ledger_balance <> ROUND(ledger_balance,2);
  IF invalid_count > 0 THEN RAISE_APPLICATION_ERROR(-20001, 'Reconcile unsupported account types, currencies, holds or fractional paise before the banking merge.'); END IF;
  SELECT COUNT(*) INTO invalid_count FROM users WHERE phone_number IN (SELECT phone_number FROM users WHERE phone_number IS NOT NULL GROUP BY phone_number HAVING COUNT(*)>1);
  IF invalid_count > 0 THEN RAISE_APPLICATION_ERROR(-20003, 'Resolve duplicate customer phone numbers before the banking merge.'); END IF;
  SELECT COUNT(*) INTO invalid_count FROM transactions WHERE amount = 0 OR amount <> ROUND(amount,2) OR status = 'PENDING';
  IF invalid_count > 0 THEN RAISE_APPLICATION_ERROR(-20002, 'Reconcile zero, fractional-paise or pending transactions before the banking merge.'); END IF;
END;
