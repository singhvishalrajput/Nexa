CREATE TABLE CUSTOMERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID VARCHAR2(26) UNIQUE REFERENCES USERS(ID),
    FULL_NAME VARCHAR2(160) NOT NULL,
    EMAIL VARCHAR2(254) NOT NULL UNIQUE,
    PHONE_NUMBER VARCHAR2(32) UNIQUE,
    DATE_OF_BIRTH DATE,
    ADDRESS VARCHAR2(255),
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL
);

CREATE TABLE ACCOUNTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCOUNT_NUMBER VARCHAR2(30) NOT NULL UNIQUE,
    CUSTOMER_ID NUMBER,
    ACCOUNT_NAME VARCHAR2(120) NOT NULL,
    ACCOUNT_TYPE VARCHAR2(20) NOT NULL,
    ACCOUNT_CATEGORY VARCHAR2(20) NOT NULL,
    CURRENCY_CODE VARCHAR2(3) DEFAULT 'INR' NOT NULL,
    VERSION NUMBER(19) DEFAULT 0 NOT NULL,
    BALANCE NUMBER(19,2) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT FK_ACCOUNTS_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(ID),
    CONSTRAINT CK_ACCOUNTS_TYPE CHECK (ACCOUNT_TYPE IN ('SAVINGS','CURRENT','CASH','CLEARING')),
    CONSTRAINT CK_ACCOUNTS_CATEGORY CHECK (ACCOUNT_CATEGORY IN ('CUSTOMER','SYSTEM')),
    CONSTRAINT CK_ACCOUNTS_STATUS CHECK (STATUS IN ('ACTIVE','BLOCKED','CLOSED')),
    CONSTRAINT CK_SYSTEM_ACCOUNT_CUSTOMER CHECK ((ACCOUNT_CATEGORY = 'SYSTEM' AND CUSTOMER_ID IS NULL) OR (ACCOUNT_CATEGORY = 'CUSTOMER' AND CUSTOMER_ID IS NOT NULL))
);

CREATE TABLE TRANSACTIONS (
    ID VARCHAR2(40) PRIMARY KEY,
    TRANSACTION_TYPE VARCHAR2(20) NOT NULL,
    SOURCE_ACCOUNT_ID NUMBER,
    DESTINATION_ACCOUNT_ID NUMBER,
    MERCHANT_NAME VARCHAR2(200),
    CATEGORY VARCHAR2(80),
    PAYMENT_METHOD VARCHAR2(32),
    AMOUNT NUMBER(19,2) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    CONSTRAINT FK_TX_SOURCE FOREIGN KEY (SOURCE_ACCOUNT_ID) REFERENCES ACCOUNTS(ID),
    CONSTRAINT FK_TX_DESTINATION FOREIGN KEY (DESTINATION_ACCOUNT_ID) REFERENCES ACCOUNTS(ID),
    CONSTRAINT CK_TX_TYPE CHECK (TRANSACTION_TYPE IN ('DEPOSIT','WITHDRAWAL','TRANSFER')),
    CONSTRAINT CK_TX_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_TX_STATUS CHECK (STATUS IN ('SUCCESS','FAILED','REVERSED')),
    CONSTRAINT CK_TX_ACCOUNTS CHECK ((TRANSACTION_TYPE='DEPOSIT' AND SOURCE_ACCOUNT_ID IS NULL AND DESTINATION_ACCOUNT_ID IS NOT NULL) OR (TRANSACTION_TYPE='WITHDRAWAL' AND SOURCE_ACCOUNT_ID IS NOT NULL AND DESTINATION_ACCOUNT_ID IS NULL) OR (TRANSACTION_TYPE='TRANSFER' AND SOURCE_ACCOUNT_ID IS NOT NULL AND DESTINATION_ACCOUNT_ID IS NOT NULL))
);

CREATE TABLE JOURNAL_ENTRIES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TRANSACTION_ID VARCHAR2(40) NOT NULL UNIQUE,
    ENTRY_REFERENCE VARCHAR2(40) NOT NULL UNIQUE,
    ENTRY_TYPE VARCHAR2(20) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT FK_JOURNAL_TRANSACTION FOREIGN KEY (TRANSACTION_ID) REFERENCES TRANSACTIONS(ID),
    CONSTRAINT CK_JOURNAL_TYPE CHECK (ENTRY_TYPE IN ('TRANSACTION','REVERSAL')),
    CONSTRAINT CK_JOURNAL_STATUS CHECK (STATUS IN ('POSTED','REVERSED'))
);

CREATE TABLE LEDGER_ENTRIES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JOURNAL_ENTRY_ID NUMBER NOT NULL,
    ACCOUNT_ID NUMBER NOT NULL,
    ENTRY_TYPE VARCHAR2(10) NOT NULL,
    AMOUNT NUMBER(19,2) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT FK_LEDGER_JOURNAL FOREIGN KEY (JOURNAL_ENTRY_ID) REFERENCES JOURNAL_ENTRIES(ID),
    CONSTRAINT FK_LEDGER_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNTS(ID),
    CONSTRAINT CK_LEDGER_TYPE CHECK (ENTRY_TYPE IN ('DEBIT','CREDIT')),
    CONSTRAINT CK_LEDGER_AMOUNT CHECK (AMOUNT > 0)
);

