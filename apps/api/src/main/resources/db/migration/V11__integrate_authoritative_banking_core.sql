INSERT INTO accounts (account_number,customer_id,account_name,account_type,account_category,balance,status,currency_code,created_at,updated_at)
SELECT a.account_number,c.id,a.display_name,a.account_type,'CUSTOMER',a.ledger_balance,
CASE a.status WHEN 'FROZEN' THEN 'BLOCKED' ELSE a.status END,a.currency_code,SYS_EXTRACT_UTC(a.created_at),SYS_EXTRACT_UTC(a.updated_at)
FROM legacy_bank_accounts a JOIN customers c ON c.user_id=a.user_id;
INSERT INTO banking_account_migration (legacy_id,account_id)
SELECT old.id,a.id FROM legacy_bank_accounts old JOIN accounts a ON a.account_number=old.account_number;
-- The cash account starts at the reconciled customer total; this is a cutover balance, not a new deposit.
INSERT INTO accounts (account_number,account_name,account_type,account_category,balance,status,created_at,updated_at)
SELECT 'SYSTEM-CASH','System cash account','CASH','SYSTEM',COALESCE(SUM(balance),0),'ACTIVE',SYS_EXTRACT_UTC(SYSTIMESTAMP),SYS_EXTRACT_UTC(SYSTIMESTAMP) FROM accounts;
-- Import history without replaying balances or inventing missing historical journal postings.
INSERT INTO transactions (id,transaction_type,source_account_id,destination_account_id,amount,status,created_at,completed_at,merchant_name,category,payment_method)
SELECT t.id,CASE WHEN t.amount>0 THEN 'DEPOSIT' ELSE 'WITHDRAWAL' END,
CASE WHEN t.amount<0 THEN m.account_id END,CASE WHEN t.amount>0 THEN m.account_id END,ABS(t.amount),
CASE t.status WHEN 'POSTED' THEN 'SUCCESS' ELSE t.status END,SYS_EXTRACT_UTC(t.occurred_at),SYS_EXTRACT_UTC(t.occurred_at),t.merchant_name,t.category,t.payment_method
FROM legacy_transactions t JOIN banking_account_migration m ON m.legacy_id=t.bank_account_id;
